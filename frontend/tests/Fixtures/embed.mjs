// Rule fixtures have four ordered fields: name, record, move, result.
// Territory fixtures have name, stones (a position, not a replay), black, white.
// An optional leading board: <positive integer> selects a size; omitted means 13.
// Result is "illegal" or the net stone-count change, including the new stone.
// SGF strings are left for each language's own decoder to interpret.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../../../fixtures/rules/', import.meta.url);
const output = new URL('./Generated.elm', import.meta.url);
function filesIn(source) {
  const files = readdirSync(source).filter(name => name.endsWith('.txt')).sort();
  if (!files.length) throw new Error(`No fixtures found in ${source.pathname}`);
  return files;
}

function parseFields(lines, keys, fail) {
  if (lines.length !== keys.length) fail(`Expected fields: ${keys.join(', ')}`);
  return Object.fromEntries(keys.map((key, i) => {
    if (!lines[i].startsWith(`${key}:`)) fail(`Expected ${key}: field, got: ${lines[i]}`);
    return [key, lines[i].slice(key.length + 1).trim()];
  }));
}

const entries = filesIn(source).map(filename => {
  const fail = message => { throw new Error(`${filename}: ${message}`); };
  const lines = readFileSync(new URL(filename, source), 'utf8').trim().split(/\r?\n/);
  const boardSize = lines[0].startsWith('board:') ? lines.shift().slice(6).trim() : '13';
  if (!/^[+]?\d+$/.test(boardSize) || !Number.isSafeInteger(Number(boardSize)) || Number(boardSize) <= 0) {
    fail(`Board size must be a positive integer, got: ${boardSize}`);
  }
  const fields = parseFields(lines, ['name', 'record', 'move', 'result'], fail);
  const result = fields.result;
  if (result !== 'illegal' && (!/^[+-]?\d+$/.test(result) || !Number.isSafeInteger(Number(result)))) {
    fail(`Expected illegal or an integer stone-count change, got: ${result}`);
  }

  return `{ filename = ${JSON.stringify(filename)}
      , name = ${JSON.stringify(fields.name)}
      , boardSize = ${Number(boardSize)}
      , record = ${JSON.stringify(fields.record)}
      , move = ${JSON.stringify(fields.move)}
      , stoneCountChange = ${result === 'illegal' ? 'Nothing' : `Just (${Number(result)})`}
      }`;
});
const territorySource = new URL('../../../fixtures/territory/', import.meta.url);
const territoryEntries = filesIn(territorySource).map(filename => {
  const fail = message => { throw new Error(`${filename}: ${message}`); };
  const lines = readFileSync(new URL(filename, territorySource), 'utf8').trim().split(/\r?\n/);
  const fields = parseFields(lines, ['name', 'stones', 'black', 'white'], fail);
  for (const color of ['black', 'white']) {
    if (!/^\d+(?:\.\d+)?$/.test(fields[color]) || !Number.isFinite(Number(fields[color]))) {
      fail(`Expected a non-negative decimal area for ${color}, got: ${fields[color]}`);
    }
  }
  return `{ filename = ${JSON.stringify(filename)}
      , name = ${JSON.stringify(fields.name)}
      , stones = ${JSON.stringify(fields.stones)}
      , black = ${Number(fields.black)}
      , white = ${Number(fields.white)}
      }`;
});

mkdirSync(new URL('.', output), { recursive: true });
writeFileSync(output, `module Fixtures.Generated exposing (Case, cases, TerritoryCase, territoryCases)

-- Generated by tests/Fixtures/embed.mjs. Do not edit.
type alias Case =
    { filename : String
    , name : String
    , boardSize : Int
    , record : String
    , move : String
    , stoneCountChange : Maybe Int
    }

cases : List Case
cases =
    [ ${entries.join('\n    , ')}
    ]

type alias TerritoryCase =
    { filename : String
    , name : String
    , stones : String
    , black : Float
    , white : Float
    }

territoryCases : List TerritoryCase
territoryCases =
    [ ${territoryEntries.join('\n    , ')}
    ]
`);
